  /* Her drawing pad: the same simple pad as her page's,
     kept in the door store as one of her top-picture choices. */
  (function initDrawPad() {
    var pad = $("dash-draw-pad");
    if (!pad || !pad.getContext) return;
    var ctx = pad.getContext("2d");
    ctx.fillStyle = "#ffffff";
    ctx.fillRect(0, 0, pad.width, pad.height);
    ctx.lineCap = "round";
    ctx.lineJoin = "round";
    var colour = "#e5484d";
    var drawing = false;
    var last = null;
    var tools = $("dash-draw-tools");
    DRAW_COLOURS.forEach(function (c, i) {
      var b = document.createElement("button");
      b.type = "button";
      b.className = "dash-draw-swatch" + (i === 0 ? " is-chosen" : "");
      b.style.setProperty("--sw", c);
      b.setAttribute("aria-label", "Colour " + c);
      b.addEventListener("click", function () {
        Array.prototype.slice.call(tools.querySelectorAll(".dash-draw-swatch")).forEach(function (x) { x.classList.remove("is-chosen"); });
        b.classList.add("is-chosen");
        colour = c;
      });
      tools.appendChild(b);
    });
    function point(evt) {
      var rect = pad.getBoundingClientRect();
      return {
        x: (evt.clientX - rect.left) * (pad.width / rect.width),
        y: (evt.clientY - rect.top) * (pad.height / rect.height)
      };
    }
    pad.addEventListener("pointerdown", function (evt) {
      drawing = true;
      last = point(evt);
      try { pad.setPointerCapture(evt.pointerId); } catch (err) { /* fine */ }
      evt.preventDefault();
    });
    pad.addEventListener("pointermove", function (evt) {
      if (!drawing || !last) return;
      var p = point(evt);
      ctx.strokeStyle = colour;
      ctx.lineWidth = 10;
      ctx.beginPath();
      ctx.moveTo(last.x, last.y);
      ctx.lineTo(p.x, p.y);
      ctx.stroke();
      last = p;
    });
    ["pointerup", "pointercancel", "pointerleave"].forEach(function (name) {
      pad.addEventListener(name, function () { drawing = false; last = null; });
    });
    var clearBtn = $("dash-draw-clear");
    if (clearBtn) clearBtn.addEventListener("click", function () {
      ctx.fillStyle = "#ffffff";
      ctx.fillRect(0, 0, pad.width, pad.height);
    });
    var saveBtn = $("dash-draw-save");
    if (saveBtn) saveBtn.addEventListener("click", function () {
      var line = $("dash-draw-line");
      var dataUrl = pad.toDataURL("image/jpeg", 0.82);
      saveBtn.disabled = true;
      call({ action: "drawing-save", token: token, dataUrl: dataUrl }).then(function (r) {
        saveBtn.disabled = false;
        if (r && r.ok) {
          hasDrawing = true;
          if (line) line.textContent = "Your picture is kept! It's one of your top-picture choices now.";
          buildPageEditorSoft();
          chirp("hum");
        } else {
          if (line) line.textContent = "That picture didn't keep. Try a smaller drawing.";
        }
      });
    });
  })();

