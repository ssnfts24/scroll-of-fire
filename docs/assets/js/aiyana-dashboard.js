  /* The same speech path the other Sparks use: the profile
     the voice layer grows from the seed (its own voice, its
     own pitch and pace), spoken by the device. */
  function speak(text, onDone) {
    try {
      var synth = window.speechSynthesis;
      if (!synth || !Voice || !spark.companion) { if (onDone) onDone(false); return false; }
      var profile = Voice.profileFor({
        seed: spark.companion.seed,
        temperament: spark.companion.temperament,
        voices: synth.getVoices ? synth.getVoices() : [],
        lang: "en"
      });
      var clean = String(text || "").replace(/\s+/g, " ").trim();
      if (!clean) { if (onDone) onDone(false); return false; }
      var utterance = new SpeechSynthesisUtterance(clean);
      if (profile) {
        var voice = (synth.getVoices ? synth.getVoices() : []).find(function (v) {
          return v.voiceURI === profile.voiceURI || v.name === profile.voiceName;
        });
        if (voice) utterance.voice = voice;
        utterance.pitch = profile.pitch;
        utterance.rate = profile.rate;
        utterance.lang = profile.lang;
      }
      if (onDone) utterance.onend = function () { onDone(true); };
      synth.cancel();
      synth.speak(utterance);
      return true;
    } catch (err) {
      if (onDone) onDone(false);
      return false;
    }
  }

