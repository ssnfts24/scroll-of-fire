  var audioCtx = null;
  function tone(freq, at, dur, gainPeak) {
    try {
      if (!audioCtx) {
        var AC = window.AudioContext || window.webkitAudioContext;
        if (!AC) return;
        audioCtx = new AC();
      }
      if (audioCtx.state === "suspended") audioCtx.resume();
      var osc = audioCtx.createOscillator();
      var gain = audioCtx.createGain();
      osc.type = "sine";
      osc.frequency.value = freq;
      var t = audioCtx.currentTime + at;
      gain.gain.setValueAtTime(0.0001, t);
      gain.gain.exponentialRampToValueAtTime(gainPeak, t + 0.03);
      gain.gain.exponentialRampToValueAtTime(0.0001, t + dur);
      osc.connect(gain);
      gain.connect(audioCtx.destination);
      osc.start(t);
      osc.stop(t + dur + 0.05);
    } catch (err) { /* sound is an offering, never a requirement */ }
  }

  /* Every sound she hears is her own Spark's voice-print:
     the chirp the core grows from its seed. */
  function chirp(kind) {
    if (!Core || !spark.companion) return;
    var c = Core.chirpFor(spark.companion);
    if (!c) return;
    if (kind === "pop") {
      tone(c.second, 0, 0.16, 0.06);
    } else if (kind === "hum") {
      tone(c.first / 2, 0, 0.55, 0.045);
    } else if (kind === "cheer") {
      tone(c.first, 0, 0.18, 0.06);
      tone(c.second, 0.14, 0.2, 0.06);
      tone(c.first * 1.5, 0.3, 0.3, 0.06);
    } else {
      tone(c.first, 0, 0.2, 0.055);
      tone(c.second, 0.16, 0.28, 0.055);
    }
  }

