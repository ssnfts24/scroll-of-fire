#!/usr/bin/env node
// Builds the World Gate's land data from the site catalog.
// Usage: node scripts/build-world-lands.mjs [--check]
//
// The lands are defined in scripts/world-lands.json over the
// site catalog (docs/data/site-catalog.json) — the registry the
// site already keeps — per the approved Codex World design
// (Nov 20, 2026): the map is generated from the catalog so it
// can never drift from the site. This script validates the
// accounting the design promises — every catalog entry is
// shelved in exactly one land, or named as the road (the
// Caravan), the sky (the Sphere), or flat by design with its
// reason — and generates docs/assets/js/world-lands.js, the
// data module the World Gate draws from.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(scriptDir, "..");
const SOURCE = path.join(ROOT, "scripts/world-lands.json");
const CATALOG = path.join(ROOT, "docs/data/site-catalog.json");
const OUT = path.join(ROOT, "docs/assets/js/world-lands.js");

export function build() {
  const source = JSON.parse(fs.readFileSync(SOURCE, "utf8"));
  const catalog = JSON.parse(fs.readFileSync(CATALOG, "utf8"));
  const byId = new Map(catalog.entries.map(e => [e.id, e]));
  const errors = [];

  const accounted = new Map(); /* entry id -> where it lives */
  const claim = (id, where) => {
    if (!byId.has(id)) errors.push(`${where}: unknown catalog entry "${id}"`);
    if (accounted.has(id)) errors.push(`catalog entry "${id}" is accounted for twice: ${accounted.get(id)} and ${where}`);
    accounted.set(id, where);
  };

  const resolve = id => {
    const e = byId.get(id);
    return e ? { id: e.id, title: e.title, path: e.path } : { id, title: id, path: null };
  };

  const lands = (source.lands || []).map(land => {
    for (const id of land.entries || []) claim(id, `land ${land.id}`);
    if (!fs.existsSync(path.join(ROOT, "docs", land.door))) {
      errors.push(`land ${land.id}: door page does not exist: ${land.door}`);
    }
    if (!fs.existsSync(path.join(ROOT, "docs", land.nextStep.href))) {
      errors.push(`land ${land.id}: next-step page does not exist: ${land.nextStep.href}`);
    }
    return {
      id: land.id,
      name: land.name,
      character: land.character,
      color: land.color,
      door: land.door,
      doorLabel: land.doorLabel,
      nextStep: land.nextStep,
      pages: (land.entries || []).map(resolve)
    };
  });

  const road = (source.road || []).map(r => {
    claim(r.entry, "the road");
    return { ...resolve(r.entry), note: r.note };
  });
  const sky = (source.sky || []).map(r => {
    claim(r.entry, "the sky");
    return { ...resolve(r.entry), note: r.note };
  });
  const flat = (source.flat || []).map(r => {
    claim(r.entry, "flat by design");
    return { ...resolve(r.entry), reason: r.reason };
  });

  for (const e of catalog.entries) {
    if (!accounted.has(e.id)) {
      errors.push(`catalog entry "${e.id}" (${e.path}) is not accounted for — shelve it in a land, or name it road, sky, or flat in scripts/world-lands.json`);
    }
  }
  if (lands.length !== 13) errors.push(`the world has thirteen lands; found ${lands.length}`);

  if (errors.length) {
    throw new Error(`world lands do not account for the catalog:\n  - ${errors.join("\n  - ")}`);
  }

  return {
    version: "world-lands/1.0.0",
    generatedFrom: "scripts/world-lands.json + docs/data/site-catalog.json",
    lands,
    road,
    sky,
    flat
  };
}

export function render(data) {
  return `"use strict";

/*
 * The Codex World's lands — GENERATED by
 * scripts/build-world-lands.mjs from scripts/world-lands.json
 * over the site catalog. Do not edit by hand; the map is drawn
 * from the catalog so it can never drift from the site.
 * Regenerate: node scripts/build-world-lands.mjs
 */
(function (root, factory) {
  const api = factory();
  if (typeof module === "object" && module.exports) {
    module.exports = api;
  }
  root.CodexWorldLands = api;
})(typeof globalThis !== "undefined" ? globalThis : this, function () {
  return ${JSON.stringify(data, null, 2)};
});
`;
}

function main() {
  const check = process.argv.includes("--check");
  const text = render(build());
  if (check) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== text) {
      console.error("docs/assets/js/world-lands.js is out of date with scripts/world-lands.json + the site catalog. Run: node scripts/build-world-lands.mjs");
      process.exit(1);
    }
    console.log("world lands are current with the catalog.");
    return;
  }
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
