#!/usr/bin/env node
/*
 * Build the Garden of Paths link graph (recommendation Q-04,
 * approved by Aaron Nov 22, 2026; program §D1, research Concept 8).
 *
 * The catalog already knows every live page, its title, and its
 * area. What it does not separate is a page's standing doors (the
 * travel bar and footer every page carries) from the paths its own
 * words point to. This generator reads each page's <main> content
 * and keeps only the links that stand in the page's own body —
 * those are the trails. Backlinks ("Who points here") are the same
 * trails read backwards. Nothing is invented: a path exists in the
 * output only because a page's own content links to it.
 *
 * Output: docs/assets/data/link-graph.json — a static file the
 * paths-from-here component reads. Regenerate after the catalog:
 *
 *   npm run site:catalog && npm run paths:graph
 *
 * `--check` compares the committed file against a fresh build and
 * exits non-zero when they differ (the test suite holds it to that).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const docs = path.join(root, "docs");
const INVENTORY = path.join(root, "site-audit", "site-master-inventory.json");
const OUTPUT = path.join(docs, "assets", "data", "link-graph.json");

export const OUT_CAP = 14;
export const IN_CAP = 14;

export function shortTitle(title) {
  return String(title || "")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/\s+[—|·]\s+Scroll of Fire.*$/, "")
    .replace(/\s*\|\s*Codex of Reality.*$/, "")
    .replace(/\s+—\s+Codex of Reality.*$/, "")
    .trim();
}

function resolveHref(pagePath, href) {
  if (!href || /^(?:#|mailto:|tel:|javascript:|data:|https?:|\/\/)/i.test(href)) return null;
  const clean = href.split("#")[0].split("?")[0];
  if (!clean) return null;
  try {
    const url = new URL(clean, `https://codexofreality.org/${pagePath}`);
    const target = decodeURIComponent(url.pathname).replace(/^\//, "");
    return target || null;
  } catch {
    return null;
  }
}

/* The page's own trails: anchors inside <main>, in the order the
 * page offers them. Pages without a <main> give their whole body
 * minus the standing furniture (nav, header, footer). */
export function contentLinks(html, pagePath, pageSet) {
  let region = html;
  const main = html.match(/<main\b[\s\S]*?<\/main>/i);
  if (main) {
    region = main[0];
  } else {
    region = html
      .replace(/<nav\b[\s\S]*?<\/nav>/gi, "")
      .replace(/<header\b[\s\S]*?<\/header>/gi, "")
      .replace(/<footer\b[\s\S]*?<\/footer>/gi, "");
  }
  const out = [];
  const seen = new Set();
  for (const match of region.matchAll(/<a\s[^>]*href="([^"]*)"[^>]*>([\s\S]*?)<\/a>/gi)) {
    const target = resolveHref(pagePath, match[1]);
    if (!target || target === pagePath || !pageSet.has(target) || seen.has(target)) continue;
    seen.add(target);
    out.push(target);
  }
  return out;
}

export function buildGraph(inventory, readPage) {
  const resources = (inventory.resources || []).filter(
    (r) =>
      typeof r.sourcePath === "string" &&
      r.sourcePath.startsWith("docs/") &&
      r.sourcePath.endsWith(".html") &&
      r.publicationStatus === "live"
  );
  const byPath = new Map();
  for (const r of resources) {
    const p = r.sourcePath.replace(/^docs\//, "");
    byPath.set(p, { path: p, title: shortTitle(r.title) || p, area: r.area || "codex" });
  }
  const pageSet = new Set(byPath.keys());

  const pages = {};
  for (const p of [...pageSet].sort()) {
    const html = readPage(p);
    const outPaths = html ? contentLinks(html, p, pageSet) : [];
    pages[p] = {
      title: byPath.get(p).title,
      area: byPath.get(p).area,
      out: outPaths.map((t) => ({ path: t, title: byPath.get(t).title, area: byPath.get(t).area })),
      in: []
    };
  }
  for (const p of Object.keys(pages)) {
    for (const link of pages[p].out) {
      pages[link.path].in.push({ path: p, title: pages[p].title, area: pages[p].area });
    }
  }
  for (const p of Object.keys(pages)) {
    pages[p].in.sort((a, b) => a.title.localeCompare(b.title));
    pages[p].outTotal = pages[p].out.length;
    pages[p].inTotal = pages[p].in.length;
    pages[p].out = pages[p].out.slice(0, OUT_CAP);
    pages[p].in = pages[p].in.slice(0, IN_CAP);
  }

  return {
    schemaVersion: 1,
    description:
      "The Garden of Paths link graph: each live page's own content links (its trails) and the pages that point to it, counted at build time from the pages as they stand. Generated by scripts/build-link-graph.mjs from the site catalog's page set; a path exists here only because a page's own words link to it.",
    generatedFrom: "site-audit/site-master-inventory.json + docs/**/*.html <main> links",
    pages
  };
}

export function renderGraph(graph) {
  return JSON.stringify(graph, null, 1) + "\n";
}

function main() {
  const check = process.argv.includes("--check");
  const inventory = JSON.parse(fs.readFileSync(INVENTORY, "utf8"));
  const graph = buildGraph(inventory, (p) => {
    const file = path.join(docs, p);
    return fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  });
  const rendered = renderGraph(graph);
  if (check) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, "utf8") : "";
    if (current !== rendered) {
      console.error("link-graph.json is stale — run: npm run paths:graph");
      process.exit(1);
    }
    console.log(`link graph check OK (${Object.keys(graph.pages).length} pages)`);
    return;
  }
  fs.writeFileSync(OUTPUT, rendered);
  console.log(`link graph written (${Object.keys(graph.pages).length} pages)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
